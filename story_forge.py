def opening_clash(text, previous):
    """هل تبدأ القصة الجديدة كسابقاتها؟"""
    first = set(re.findall(r"[\w؀-ۿ]+", text.split("\n")[0].lower())[:9])
    if len(first) < 4:
        return False
    for old in previous:
        prev = set(re.findall(r"[\w؀-ۿ]+", old.lower())[:9])
        if prev and len(first & prev) / len(first) > 0.55:
            return True
    return False


