def _worker(job_id, dna, fmt, dialect, core, pov, drama, provider, creds, mode):
    job = JOBS[job_id]
    heat = job.get("heat", "hot")
    try:
        if job.get("kind") in TOPIC_KINDS:
            write_info(job, dna, fmt, dialect, provider, creds, mode, heat)
        else:
            write_story(job, dna, fmt, dialect, core, pov, drama, provider, creds, mode, heat)
    except Cancelled:
        job["stage"] = "cancelled"
    except Exception as exc:
        log.exception("write failed")
        job["stage"] = "error"
        job["error"] = str(exc)


def _creds(data):
    provider = "openai" if data.get("provider") == "openai" else "free"
    think = (data.get("think") or "").strip()
    creds = {"base": (data.get("base") or "").strip(),
             "key": (data.get("key") or "").strip(),
             "model": (data.get("model") or "").strip(),
             "plan_model": (data.get("plan_model") or "").strip(),
             "think": think if think in THINK_LEVELS else ""}
    return provider, creds


def _snapshot(job):
    return {k: v for k, v in dict(job).items() if k not in ("at", "cancel")}


