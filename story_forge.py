def _guard(job):
    if job.get("cancel"):
        raise Cancelled()


def plan_creds(creds):
    """بيانات المزوّد لمرحلة الحبكة: نموذج أقوى إن حُدّد، وإلا نفس النموذج."""
    model = creds.get("plan_model") or OPENAI_PLAN_MODEL
    return dict(creds, model=model) if model else creds


def write_story(job, dna, fmt, dialect, core, pov, drama, provider, creds, mode="full", heat="hot"):
    seen_plots = recent_plots()
    prev_openings = recent_openings()
    blocked = TIRED_PLOTS + seen_plots
    ending = CORES.get(core, CORES["betrayal"])[3]
    system = {"role": "system", "content": system_prompt(dialect)}

    def token(piece, notice):
        _guard(job)
        if notice:
            job["notice"] = notice
        elif piece:
            job.pop("notice", None)
            job["text"] += piece

    # 1. الحبكة وورقة الحقائق
    job["stage"] = "premise"
    ideas = parse_ideas(chat(
        [system, {"role": "user", "content": premise_prompt(dna, core, drama, seen_plots)}],
        provider, plan_creds(creds), temperature=1.05, timeout=150))
    idea, novelty = pick_idea(ideas, blocked)
    facts = idea["facts"]
    job["premise"] = premise_text(idea)
    job["facts"] = facts
    job["novelty"] = novelty
    _guard(job)

    # 2. المسودة — تُبثّ حرفًا حرفًا
    job["stage"] = "draft"
    job["text"] = ""
    draft = clean(chat(
        [system, {"role": "user", "content": write_prompt(dna, idea, fmt, dialect, core, pov, drama, heat)}],
        provider, creds, on_token=token, timeout=200))
    _guard(job)

    # 3. التحرير — يشدّ كل سطر، ويُبثّ كذلك
    job["stage"] = "edit"
    job["text"] = ""
    final = clean(chat(
        [system, {"role": "user", "content": edit_prompt(fmt, pov, ending, facts, dialect, heat)
                  + "\n\nالمسودة:\n" + draft}],
        provider, creds, on_token=token, temperature=0.75, timeout=200))
    _guard(job)

    # 4. التدقيق المنطقي — يُتخطّى في الوضع السريع
    job["text"] = final
    if mode != "fast":
        job["stage"] = "audit"
        try:
            checked = json_obj(chat(
                [system, {"role": "user", "content": audit_prompt(facts, ending, core) + "\n\nالنص:\n" + final
                          + "\n\nالأرقام الواردة فيه: " + "، ".join(numbers_in(final))}],
                provider, creds, temperature=0.3, timeout=150))
            fixed = clean(str(checked.get("text") or ""))
            issues = [str(x) for x in checked.get("issues", [])][:6]
            if word_count(fixed) >= word_count(final) * 0.6:
                final = fixed
            job["issues"] = issues
        except Cancelled:
            raise
        except Exception as exc:
            log.warning("تعذّر التدقيق: %s", exc)
            job["issues"] = []
        _guard(job)

    # 5. الفحوصات المحلية، ثم جولة صقل واحدة إن رسب فحص جوهري
    checks = run_checks(final, fmt, pov, ending, facts, prev_openings, dialect)
    problems = polish_problems(checks)
    if problems:
        job["stage"] = "polish"
        job["text"] = final
        try:
            candidate = clean(chat(
                [system, {"role": "user",
                          "content": polish_prompt(problems, fmt, pov, ending, facts, dialect)
                          + "\n\nالنص:\n" + final}],
                provider, creds, temperature=0.5, timeout=150))
            new_checks = run_checks(candidate, fmt, pov, ending, facts, prev_openings, dialect)
            if (score_of(new_checks) >= score_of(checks)
                    and word_count(candidate) >= word_count(final) * 0.6):
                final, checks = candidate, new_checks
                job["polished"] = True
        except Cancelled:
            raise
        except Exception as exc:
            log.warning("تعذّر الصقل: %s", exc)
    _guard(job)

    # 6. افتتاحية تشبه محفوظًا سابقًا → بدائل واختيار الأبعد
    if any(c["id"] == "opening" and not c["ok"] for c in checks):
        job["stage"] = "hook"
        try:
            pick = best_hook(make_hooks(final, provider, creds, dialect), prev_openings)
            if pick:
                final = pick + "\n" + "\n".join(final.split("\n")[1:])
                checks = run_checks(final, fmt, pov, ending, facts, prev_openings, dialect)
                job["rehooked"] = True
        except Cancelled:
            raise
        except Exception as exc:
            log.warning("تعذّر تبديل الافتتاحية: %s", exc)

    if fmt == "thread":
        parts = split_thread(final)
        job["parts"] = parts
        final = thread_text(parts)
    job["text"] = final
    job["words"] = word_count(final)
    job["numbers"] = count_numbers(final)
    job["cliches"] = [b for b in BANNED if b in final]
    job["checks"] = checks
    job["score"] = score_of(checks)
    job["plot"] = idea["hidden"]
    job["stage"] = "done"


