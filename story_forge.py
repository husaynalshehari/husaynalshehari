def premise_text(idea):
    parts = [idea["hidden"]]
    if idea.get("why_hidden"):
        parts.append("لماذا بقي مخفيًا: " + idea["why_hidden"])
    if idea.get("why_now"):
        parts.append("لماذا ظهر الآن: " + idea["why_now"])
    if idea.get("evidence"):
        parts.append("الدليل بحرفه، يُقتبس في سطر مستقل: " + idea["evidence"])
    if idea.get("motive"):
        parts.append("دافع الطرف الآخر: " + idea["motive"])
    return "\n".join(parts)


