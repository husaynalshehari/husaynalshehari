def norm_digits(text):
    return text.translate(AR_DIGITS)


def numerals(text):
    """الأرقام في النص كسلاسل ASCII، مع دمج فواصل الآلاف."""
    text = re.sub(r"(\d)[,،٬](\d{3})", r"\1\2", norm_digits(text))
    return re.findall(r"\d+", text)


def numbers_in(text):
    return re.findall(r"[0-9٠-٩]+", text)


def count_numbers(text):
    """الأرقام المكتوبة بالأرقام فقط: «9 سنين» تُحسب، «تسع سنين» لا — لأن الرقم هو ما يُصدَّق."""
    return len(re.findall(r"[0-9٠-٩]+", text))


def word_count(text):
    return len(re.findall(r"[\w؀-ۿ]+", text))


def clean(text):
    text = re.sub(r"^```.*?$|^```$", "", text.strip(), flags=re.M)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip()


def words_of(text):
    text = TASHKEEL.sub("", text.lower())
    return {w for w in re.findall(r"[\w؀-ۿ]{3,}", text) if w not in STOP}


def overlap(a, b):
    """نسبة الكلمات المشتركة: تكشف الفكرة القصيرة الفارغة والفكرة التي تبتلع حبكة مستهلكة."""
    wa, wb = words_of(a), words_of(b)
    common = len(wa & wb)
    return max(common / max(1, len(wa)), common / max(1, len(wb)))


def count_leaks(text):
    return len(re.findall(r"(?:^|\s)(?:أنا|كنت|لي|عندي|أنّي|إني)(?=\s|$|[،.])", text))


def strip_thread_numbers(text):
    return "\n".join(re.sub(r"^\s*[\d٠-٩]+\s*[).\-–:/]\s*", "", ln)
                     for ln in text.split("\n"))


def _pack(lines, limit):
    """يجمّع الأسطر في أجزاء لا يتجاوز الواحد الحدّ؛ السطر الأطول من الحدّ يُقصّ عند مسافة."""
    parts, cur = [], ""
    for ln in lines:
        while len(ln) > limit:                      # سطر وحده أطول من الحدّ
            cut = ln.rfind(" ", 0, limit) or limit
            piece, ln = ln[:cut].rstrip(), ln[cut:].lstrip()
            if cur:
                parts.append(cur)
                cur = ""
            parts.append(piece)
        cand = (cur + "\n\n" + ln) if cur else ln
        if cur and len(cand) > limit:
            parts.append(cur)
            cur = ln
        else:
            cur = cand
    if cur:
        parts.append(cur)
    return parts


def split_thread(text, limit=THREAD_MAX):
    """يقسّم القصة إلى أجزاء ثريد: الجزء الأول ينتهي عند علامة «---» (الفجوة)، والباقي يُجمَّع آليًا."""
    lines = [ln.strip() for ln in text.split("\n") if ln.strip()]
    if not lines:
        return []
    if "---" in lines:
        i = lines.index("---")
        head, tail = lines[:i], [ln for ln in lines[i + 1:] if ln != "---"]
    else:                                           # بلا علامة: أول سطر ينتهي بنقطتين بعد الثلث الأول
        n, cut = len(lines), None
        for j in range(max(1, n // 3), n - 1):
            if lines[j].endswith(("..", "…")):
                cut = j + 1
                break
        if cut is None:
            cut = max(1, round(n * 0.45))
        head, tail = lines[:cut], lines[cut:]
    if not head or not tail:
        mid = max(1, len(lines) // 2)
        head, tail = lines[:mid], lines[mid:]
    return _pack(head, limit) + _pack(tail, limit)


def thread_text(parts):
    return "\n\n---\n\n".join(parts)


def stray_numbers(text, facts, fmt="medium"):
    """أرقام في النص لا تطابق ورقة الحقائق. الأعداد ١ و٢ لا تُحسب."""
    if not facts:
        return []
    body = strip_thread_numbers(text) if fmt == "thread" else text
    known = set(numerals(" ".join(facts)))
    for n in list(known):
        known.add(n + "000")                      # «40 ألف» تغطي 40000
        if n.endswith("000") and len(n) > 3:
            known.add(n[:-3])
    return sorted({n for n in numerals(body) if n not in known and int(n) > 2}, key=int)


def json_obj(raw):
    raw = re.sub(r"^```(?:json)?\s*|\s*```$", "", raw.strip(), flags=re.M).strip()
    try:
        return json.loads(raw, strict=False)
    except ValueError:
        m = re.search(r"\{.*\}", raw, re.S)
        if m:
            try:
                return json.loads(m.group(), strict=False)
            except ValueError:
                pass
    raise RuntimeError("ردّ غير مفهوم من المزوّد.")


