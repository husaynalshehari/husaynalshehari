def info_text(spec):
    cfg = topic_cfg(spec.get("kind"))
    d = cfg["domains"][spec["domain"]]
    a = cfg["angles"][spec["angle"]]
    lines = [
        f"- المجال: {d[0]} — {d[1]}",
        f"- زاوية المنشور: {a[0]} — {a[1]}",
        f"- الإطار: {spec['frame']}",
    ]
    if spec.get("topic"):
        lines.insert(0, f"- الموضوع الذي طلبه الكاتب، وله الأولوية: {spec['topic']}")
    return "\n".join(lines)


